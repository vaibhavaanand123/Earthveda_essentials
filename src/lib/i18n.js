import { useSyncExternalStore } from 'react';
let language = 'de';
try {
  language = localStorage.getItem('earthveda-language') === 'en' ? 'en' : 'de';
} catch {}
const listeners = new Set();
const subscribe = (cb) => {
  listeners.add(cb);
  return () => listeners.delete(cb);
};
export const getLanguage = () => language;
export function setLanguage(next) {
  if (!['de', 'en'].includes(next)) return;
  language = next;
  try {
    localStorage.setItem('earthveda-language', next);
  } catch {}
  document.documentElement.lang = next;
  for (const listener of listeners) listener();
}
export function useLanguage() {
  const lang = useSyncExternalStore(subscribe, getLanguage, () => 'de');
  return { language: lang, setLanguage, t };
}
export function t(en, de) {
  return language === 'de' ? (de ?? DICTIONARY[en] ?? en) : en;
}
